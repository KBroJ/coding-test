'''
[괄호 없는 사칙연산]_https://www.acmicpc.net/problem/16503
-----------------------------------------------------------------------
사칙연산에서 곱셈과 나눗셈은 덧셈과 뺄셈보다 먼저 계산한다.
덧셈과 뺄셈을 먼저 계산하고 싶을 때는 보통 가장 큰 연산 우선순위를 가지는 괄호를 사용하여 연산 순서를 지정한다.
예를 들어, 아래의 식은 연산 순서에 따라 두 가지 다른 결과가 나올 수 있다.

(2 + 3) × 4 = 20
2 + (3 × 4) = 14
연산 우선순위가 같은 곱셈과 나눗셈 또는 덧셈과 뺄셈만 있는 식에서는 보통 왼쪽에서 오른쪽 순서로 연산을 한다.
하지만 이런 상황에도 연산 순서에 따라 아래와 같이 두 가지 다른 결과가 나올 수 있다.

(6 ÷ 2) × 3 = 9
6 ÷ (2 × 3) = 1
만약 곱셈, 나눗셈, 덧셈, 뺄셈의 4가지 연산자의 연산 우선순위가 동등하다고 할 때,
괄호 없는 식에서 서로 다른 연산 순서의 계산 결과를 구하여라.
-----------------------------------------------------------------------
첫 번째 줄에는 "K1 O1 K2 O2 K3" 형태로 식이 주어진다.
정수 Ki (1 ≤ Ki ≤ 1,000)는 피연산자를,
문자열 Oi는 곱셈(*), 나눗셈(/), 덧셈(+), 뺄셈(-) 중 한 가지 연산자를 의미한다.

나눗셈 연산은 정수 나눗셈으로 몫만 취하며,
피연산자 중 하나가 음수이면 양수로 바꿔 계산한 결괏값에 음수를 취한다.
또한, 계산 과정에서 0으로 나누어야 하는 식은 주어지지 않는다.

주어진 식에서 서로 다른 연산 순서의 계산 결과가 작은 것을 첫 번째 줄에, 큰 것을 두 번째 줄에 출력한다.
-----------------------------------------------------------------------
예제 입력
    2 + 3 * 4
예제 출력
    14
    20

========================================================================================================================
생각하기
    입력 정수는 3개
    앞 () 값과 뒤 ()한 값을 각각 저장

'''
import sys
input = sys.stdin.readline

def calc(x, op, y):
    if op == '+': return x + y
    elif op == '-': return x - y
    elif op == '*': return x * y
    elif op == '/':
        if x * y > 0:               # 두 수의 부호가 같으면 (양수*양수, 음수*음수) → 결과 양수
            return x // y           # // : 정수 나눗셈 (Java의 /와 동일, 소수점 버림)
        elif x * y < 0:             # 두 수의 부호가 다르면 → 결과 음수
            return -(abs(x) // abs(y))  # abs()로 절댓값 나눗셈 후 음수 부호 붙이기
        else:                       # x == 0 이면 결과는 항상 0 (0 / 어떤수 = 0)
            return 0

def four_operation():
    # 입력
    a, b, c, d, e = map(str, input().split())
    a, c, e = int(a), int(c), int(e)

    result1 = calc(calc(a, b, c), d, e)
    result2 = calc(a, b, calc(c, d, e))

    if result1 < result2:
        print(result1)
        print(result2)
    else:
        print(result2)
        print(result1)


# 입력
four_operation()

