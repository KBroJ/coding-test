'''
[알고리즘 수업 - 선택 정렬 5]_https://www.acmicpc.net/problem/23899
-----------------------------------------------------------------------
오늘도 서준이는 선택 정렬 수업 조교를 하고 있다. 아빠가 수업한 내용을 학생들이 잘 이해했는지 문제를 통해서 확인해보자.

N개의 서로 다른 양의 정수가 저장된 배열 A가 있다.
선택 정렬로 배열 A를 오름차순 정렬할 경우 정렬 과정에서 배열 A가 배열 B와 같은 경우가 발생하는지 확인해 보자. 초기 상태 배열 A도 정렬 과정에서 발생 가능한 경우로 생각하자.

크기가 N인 배열에 대한 선택 정렬 의사 코드는 다음과 같다.

selection_sort(A[1..N]) { # A[1..N]을 오름차순 정렬한다.
    for last <- N downto 2 {
        A[1..last]중 가장 큰 수 A[i]를 찾는다
        if (last != i) then A[last] <-> A[i]  # last와 i가 서로 다르면 A[last]와 A[i]를 교환
    }
}
-----------------------------------------------------------------------
첫째 줄에 배열 A, B의 크기 N(5 ≤ N ≤ 10,000)이 주어진다.
다음 줄에 서로 다른 배열 A의 원소 A1, A2, ..., AN이 주어진다. (1 ≤ Ai ≤ 109)
다음 줄에 서로 다른 배열 B의 원소 B1, B2, ..., BN이 주어진다. (1 ≤ Bi ≤ 109)

선택 정렬로 배열 A를 오름차순 정렬하는 과정에서 배열 A가 배열 B와 같은 경우가 발생하면 1, 아니면 0을 출력한다.
-----------------------------------------------------------------------
예제 입력
5
3 1 2 5 4
2 1 3 4 5

예제 출력
1
========================================================================================================================
생각하기
    선택정렬(Selection Sort)
        가장 작은 데이터를 선택해 맨 앞에 있는 데이터와 바꾸고, 그 다음 작은 데이터를 선택해 앞에서 두번째 데이터와 바꾸는 과정을 반복

    하지만 문제에서 의사코드를 줬으므로 의사코드를 기준으로 진행해야함
         for last <- N downto 2 {                   // last가 N부터 2까지 1씩 줄어들며 반복
            A[1..last]중 가장 큰 수 A[i]를 찾는다
            if (last != i) then A[last] <-> A[i]  # last와 i가 서로 다르면 A[last]와 A[i]를 교환
        }
'''
import sys
input = sys.stdin.readline

def method():

    N = int(input())
    A = list(map(int, input().split()))
    B = list(map(int, input().split()))

    result = 0

    # 선 비교
    if A == B:
        result = 1
        return print(result)

    for last in range(N - 1, 0, -1):
        max_idx = 0

        for j in range(1, last + 1):  # 최댓값 인덱스 찾기
            if A[j] > A[max_idx]:
                max_idx = j

        if last != max_idx:  # 한 번만 교환
            A[last], A[max_idx] = A[max_idx], A[last]

        if A == B:
            result = 1
            break

        print("A : ", A)
        print("B : ", B)

    return print(result)

method()
