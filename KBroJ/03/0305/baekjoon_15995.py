'''
[잉여역수 구하기]_https://www.acmicpc.net/problem/15995
-----------------------------------------------------------------------
지민이는 대학교에서 "잉여역수 구하기"라는 강의를 듣고 있는데, 지민이는 정수론을 싫어해서 수업 시간에 그냥 졸다 나왔다.
그래서 혁주에게 "오늘 숙제 뭐야?"라고 물었더니,
혁주가 "서로소인 두 자연수 a와 m의 값이 주어지면 a의 법 m에 대한 잉여역수 a*를 구하는 거야."라고 말했다.
지민이는 수업을 듣지 않아서 잉여역수의 정의를 모른다.
지민이의 숙제를 우리가 대신해 주자.
-----------------------------------------------------------------------
첫째 줄에 서로소인 두 자연수 a와 m이 사이에 공백을 두고 주어진다.
(2 ≤ a, m ≤ 10,000)

첫째 줄에 a의 법 m에 대한 잉여역수 a*를 출력한다.
단, 잉여역수는 무한히 많기 때문에 그 중 자연수이며, 최소인 값을 출력하도록 한다.
-----------------------------------------------------------------------
예제 입력
3 4

예제 출력
3
========================================================================================================================
생각하기
    a의 법 m에 대한 잉여역수 a*를 구하기

        법 m 세계란?
            m-1 다음 다시 0으로 돌아감
            ex)
                0, 1, 2, 3, ..., m,
                0, 1, 2, 3, ..., m, ...


    a의 법 m의 세계 : [a와 곱한결과]를 [m]으로 나누었을 때 나머지가 1이 되는 값
    역수 : 곱하면 1이 되는 정수
        ex) 3의 역수 : 1/3

    [ a x ? ] % m = 1



'''
import sys
input = sys.stdin.readline

def method():

    a, m = map(int, input().split())

    a_star = 1
    while True:
        if (a * a_star) % m == 1:
            print(a_star)
            break
        a_star += 1

method()
# ========================================================================================================================
'''
정리

[알고리즘]
    완전탐색 / 브루트포스
    - 1부터 하나씩 시도해서 조건을 만족하는 첫 번째 값 찾기

[풀이 방법]
    잉여역수 정의: (a × a*) % m == 1 을 만족하는 가장 작은 자연수 a*
    → a* = 1부터 시작해서 조건 만족할 때까지 while True로 반복
    → 조건 만족하면 출력 후 break

[이상적인 풀이]
    현재 풀이가 가장 직관적인 형태
    수학적으로는 확장 유클리드 알고리즘으로 O(log n)에 풀 수 있지만
    이 문제 범위(a, m ≤ 10,000)에서는 브루트포스로 충분

[어려웠던 부분] 잉여역수 개념 이해
    "법 m" = m으로 나눈 나머지 세계 = % m
    "역수" = 곱하면 1이 되는 수

    법 m 세계에서는 소수(1/3 등)가 없고 정수만 존재
    → 곱한 결과를 m으로 나눈 나머지가 1이 되는 정수를 역수로 사용

    일반 세계:  3 × (1/3) = 1
    법 4 세계:  3 × 3 = 9,  9 % 4 = 1  ✅

'''