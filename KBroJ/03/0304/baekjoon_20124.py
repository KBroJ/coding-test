'''
[모르고리즘 회장님 추천 받습니다]_https://www.acmicpc.net/problem/20124
-----------------------------------------------------------------------
국렬이는 모르고리즘 차기 회장을 빠르게 구해야 한다. 안 그러면 대학원 가서도 회장을 해야 하기 때문이다.
그래서 국렬이는 어떻게든 2020년 연세대학교 프로그래밍 경진대회를 열어서 차기 회장을 선택하려고 했으나, 코로나19 때문에 미루고 결국 11월에 개최하게 되었다.
국렬이는 대회를 치른 사람 중에서 점수가 가장 높은 사람을 억지로 차기 회장으로 지목하려고 한다.
만약에 가장 높은 사람이 2명 이상 있는 경우, 이름이 사전 순으로 가장 앞선 사람을 차기 회장으로 뽑을 것이다.
차기 회장으로 누가 지목될지 알아내라.
-----------------------------------------------------------------------
다음과 같이 입력이 주어진다.
N
A1 B1
. . . . . .
AN BN

첫째 줄에 차기 회장으로 뽑힐 사람의 이름을 출력하여라.
-----------------------------------------------------------------------
예제 입력
    3
    inseop 10
    gukryeol 1
    juno 11
예제 출력
    juno
========================================================================================================================
생각하기
    N 입력받기
    N 번 반복하여 입력받기
'''
import sys
input = sys.stdin.readline

def method():

    N = int(input())

    winner = ""
    max_score = 0

    for i in range(N):

        name, score = input().split()
        score = int(score)

        if score > max_score:
            winner = name
            max_score = score
        elif score == max_score:
            if name < winner:
                winner = name
                max_score = score

    return print(winner)

method()
# ========================================================================================================================
