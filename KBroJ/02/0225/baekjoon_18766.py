'''
[카드 바꿔치기]_https://www.acmicpc.net/problem/18766
-----------------------------------------------------------------------
범고래와 돌고래는 카드놀이를 좋아한다.
각 카드는
빨강 (R), 노랑 (Y), 파랑 (B) 중 하나의 색으로 칠해져 있고
0-9 사이의 숫자가 적혀있다.

색과 숫자가 같은 카드가 여러 장 있을 수도 있다.

최근 범고래는 모든 게임에서 졌고, 돌고래가 몰래 카드를 바꿔치기 한다는 의심을 하게 되었다.

범고래는 기억력이 매우 좋아서
카드놀이를 하기 전 n장의 카드와
카드놀이를 하면서 둘이 플레이 한 n장의 카드를 모두 기억하고 있다.
하지만 돌고래가 카드를 바꿔치기 했는지 아닌지 판단을 하는 능력은 부족하다.

예를 들어, 카드놀이를 하기 전에 n = 5장의 카드가 있었고, 이 카드는 아래와 같았다고 하자.
    R0
    B9
    R5
    Y3
    R2

카드놀이를 마치고 난 뒤 범고래가 기억하는 카드는 다음과 같다.
    R0
    B8
    R5
    Y3
    R2

이런 경우는 돌고래가 B9 카드 대신 B8 카드로 바꿔치기를 한 것이다.

돌고래가 카드 바꿔치기를 한 증거가 있는지 아닌지 판단하는 프로그램을 만들어보자.
-----------------------------------------------------------------------
첫 줄에 테스트 케이스의 수 T가 주어진다.
각 테스트 케이스는 다음과 같이 세 줄로 이루어져 있다.
    첫째 줄에
        카드의 개수 n이 주어진다.
    둘째 줄에
        카드놀이를 하기 전 범고래가 기억하는 n장의 카드를 나타내는 n개의 문자열이 공백으로 구분되어 주어지는데,
        각 문자열은 두 글자이며 첫 글자는 R, Y, B 중 하나이고 두 번째 글자는 숫자 0-9중 하나이다.
    셋째 줄에는
        카드놀이가 끝난 후 범고래가 기억하는 n장의 카드가 주어진다. 입력 형식은 둘째 줄과 같다.

각각의 테스트 케이스마다 한 줄에 하나씩 돌고래가 카드를 바꿔치기 했으면 "CHEATER"를, 아니면 "NOT CHEATER"를 따옴표 없이 출력한다.
-----------------------------------------------------------------------
예제 입력
    4
    5
    R0 B9 R5 Y3 R2
    R0 B8 R6 Y3 R2
    1
    R0
    R0
    3
    R1 R0 R0
    R0 R1 R1
    3
    R1 R1 R0
    R0 R1 R1
예제 출력
    CHEATER
    NOT CHEATER
    CHEATER
    NOT CHEATER

========================================================================================================================
생각하기
    첫번째 입력값 T 만큼 반복
        입력받기
            카드의 수 : n
            카드놀이 하기 전 n개의 카드 값들 : arr1
            카드놀이 하기 후 n개의 카드 값들 : arr2
        n 만큼 반복
            arr1[i] 과 arr2[i] 비교
====> 
    카드 순서와 상관없이 구성만 같으면 되므로 sorted 사용한뒤 == 로 일치여부 판단

'''
import sys
input = sys.stdin.readline

def find_cheater():

    T = int(input())

    for i in range(T):
        n = int(input())
        beforeCard = sorted(list(map(str, input().split())))
        afterCard = sorted(list(map(str, input().split())))

        if beforeCard != afterCard:
            print("CHEATER")
        else:
            print("NOT CHEATER")


find_cheater()
# ========================================================================================================================
'''
정리

[알고리즘]
    정렬 후 비교 (Sort & Compare)
    - 두 리스트를 정렬해서 순서를 통일한 뒤 동일한지 비교

[풀이 방법]
    카드 순서는 게임 중에 섞일 수 있으므로 인덱스별 비교는 틀림
    → 두 리스트를 각각 정렬해서 구성이 같은지 비교
        beforeCard = sorted([...])
        afterCard  = sorted([...])
        beforeCard != afterCard → CHEATER

[이상적인 풀이]
    현재 풀이가 이미 가장 간결한 형태
    sorted() 후 리스트 == 비교는 한 줄로 처리 가능하고 가독성도 좋음

    추가로 Counter를 쓰는 방법도 있음 (딕셔너리로 개수 비교)
        from collections import Counter
        Counter(beforeCard) != Counter(afterCard) → CHEATER
    → 정렬 없이 O(n)으로 처리 가능하지만 이 문제에선 큰 차이 없음

[어려웠던 부분] 인덱스 비교 vs 구성 비교
    처음에 beforCard[i] != afterCard[i] 로 인덱스별 비교했는데
    카드 순서가 바뀌어도 같은 카드면 NOT CHEATER이므로 틀림

    Before: R1 R1 R0  →  sorted: [R0, R1, R1]
    After:  R0 R1 R1  →  sorted: [R0, R1, R1]
    → 정렬하면 같으므로 NOT CHEATER

'''